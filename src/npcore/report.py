"""Turn results/release_*.json into results/RESULTS.md (the tables used in README and docs/04-evaluation.md)."""
from __future__ import annotations

import json
import pathlib

NAMES = {"zt_alert": "Zero-trust baseline, SOC alerts", "zt_auto": "Zero-trust baseline, automatic containment",
         "zt_strong": "Zero-trust baseline + correlation + decoys",
         "nt v0.1": "Zero trust + NullProtocol Negative Trust v0.1", "nt v0.2": "Zero trust + NullProtocol Negative Trust v0.2",
         "nt v0.3": "Zero trust + NullProtocol Negative Trust v0.3", "nt v0.4": "**Zero trust + NullProtocol Negative Trust v0.4**",
         "nt v0.3 tuned": "Zero trust + NullProtocol Negative Trust v0.3, tuned weights"}
ORDER = ["zt_alert", "zt_auto", "zt_strong", "nt v0.1", "nt v0.2", "nt v0.3", "nt v0.4", "nt v0.3 tuned"]


def _f(x, suf=""):
    if x is None:
        return "–"
    if isinstance(x, (list, tuple)):
        return f"{x[0]:.2f}"
    return f"{x}{suf}"


def sim_table(S: dict, archs=ORDER) -> list:
    L = ["| Architecture | Harm prevented | Attacks contained | Median h to containment | Victim blamed | Careless employee over-contained | Innocents contained / 1,000 user-days | Innocent step-ups / 1,000 user-days |",
         "|---|---|---|---|---|---|---|---|"]
    for a in archs:
        if a in S:
            r = S[a]
            L.append(f"| {NAMES[a]} | {_f(r['harm_prevented_pct'], ' %')} | {_f(r['containment_rate_pct'], ' %')} | {_f(r['median_hours_to_contain'])} | "
                     f"{_f(r['victim_blamed_pct'], ' %')} | {_f(r['negligent_over_contained_pct'], ' %')} | "
                     f"{_f(r['innocent_contained_per_1000_user_days'])} | {_f(r['innocent_stepups_per_1000_user_days'])} |")
    return L


def cert_table(C: dict) -> list:
    L = ["| Architecture | Incidents detected | Scenario 1 | Scenario 2 | Scenario 3 | Innocent users ever restricted / 1,000 | Case precision |",
         "|---|---|---|---|---|---|---|"]
    for a in ORDER:
        if a in C:
            r = C[a]
            restricted = "alerts only" if a == "zt_alert" else _f(r["false_l3_users_per_1000"])
            L.append(f"| {NAMES[a]} | {r['detected_pct']} % | {r['s1:detected_pct']} % | {r['s2:detected_pct']} % | {r['s3:detected_pct']} % | "
                     f"{restricted} | {_f(r['case_precision_pct'], ' %')} |")
    return L


def write_report(out: pathlib.Path) -> str:
    L = ["# Results (v0.9)", "", "Generated by `npcore report` from `results/release_*.json`. Method: [docs/04-evaluation.md](../docs/04-evaluation.md).",
         "", "NullProtocol Negative Trust is an extension of zero trust. The zero-trust baselines are our own re-implementations",
         "inside the same engine and simulator (same signals, same enforcement points), not commercial products.", ""]
    p = out / "release_sim.json"
    if p.exists():
        r = json.loads(p.read_text())
        for g, title in (("office", "Simulation, fresh seeds 301-320 (office organisation)"),
                         ("unseen_profiles", "Simulation, organisation types not used for development or tuning (remote-first, night-shift; seeds 601-610)")):
            for ss, st in (("standard", "standard attacks"), ("adaptive", "attackers who know the defences"),
                           ("cases", "reconstructions of eight documented incidents")):
                if ss in r[g]:
                    L += [f"## {title}: {st}", ""] + sim_table(r[g][ss]) + [""]
        cases = r["office"].get("cases")
        if cases:
            from .sim_cases import CASE_SCENARIOS
            L += ["## Per incident (office, seeds 301-320): contained % / data stopped %", "",
                  "| Configuration | " + " | ".join(CASE_SCENARIOS) + " |", "|---|" + "---|" * len(CASE_SCENARIOS)]
            for a in ("zt_auto", "zt_strong", "nt v0.3", "nt v0.4"):
                if a in cases:
                    L.append(f"| {NAMES[a]} | " + " | ".join(f"{cases[a][t + ':contained_pct']:.0f} / {_f(cases[a][t + ':harm_prevented_pct'])}"
                                                           for t in CASE_SCENARIOS) + " |")
            L.append("")
    p = out / "release_cert.json"
    if p.exists():
        L += ["## CERT r4.2 (Carnegie Mellon), calibrated shadow-mode replay", ""] + cert_table(json.loads(p.read_text())) + [""]
    p = out / "release_scale.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += [f"## 1,000 employees × 90 days, 36 attacks per organisation ({r['events_per_run']:,} events)", ""] + \
             sim_table(r["summary"], ["zt_strong", "nt v0.3", "nt v0.4"]) + ["",
             "Events per second (one core, including the evaluation harness): " +
             ", ".join(f"{NAMES[k].strip('*')} {v:,}" for k, v in r["events_per_second"].items()), ""]
    p = out / "tuning.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += ["## Cross-organisation tuning", "",
              "Tuned on office, USB-culture and finance-heavy organisations; tested on remote-first and night-shift organisations.", "",
              "| Architecture | Objective, default weights | Objective, tuned weights |", "|---|---|---|"]
        for a, n in (("nt_no_sentiment", "Zero trust + NullProtocol Negative Trust v0.3"), ("zt_strong", "Zero-trust baseline + correlation + decoys")):
            L.append(f"| {n} | {r[a]['test_default']['utility']:.1f} | {r[a]['test_tuned']['utility']:.1f} |")
        L.append("")
    p = out / "splunk_okta.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += ["## Recorded Okta attack logs (splunk/attack_data)", "",
              "Expected detection fixed before each run from the dataset's description.", "",
              "| Dataset | MITRE | Events | Expected | v0.4 | v0.5 |", "|---|---|---|---|---|---|"]
        for k, v in r.items():
            L.append(f"| {k} | {v['technique']} | {v['events_mapped']} | {', '.join(v['expected']) or 'nothing'} | "
                     f"{'detected' if v['v0.4']['as_expected'] else 'missed'} | {'detected' if v['v0.5']['as_expected'] else 'missed'} |")
        L.append(f"\nAs expected: v0.4 {sum(v['v0.4']['as_expected'] for v in r.values())}/{len(r)}, "
                 f"v0.5 {sum(v['v0.5']['as_expected'] for v in r.values())}/{len(r)}.\n")
    p = out / "splunk_cloud.json"
    if p.exists():
        r = json.loads(p.read_text())
        sc = [v for v in r.values() if "v0.6" in v]
        L += ["## Recorded cloud attack logs (splunk/attack_data)", "",
              "Expected detection fixed before the first run from each dataset's name. First-run results; no rule was "
              "changed after seeing them.", "",
              "| Dataset | Source | Events | Expected | v0.5 | v0.6 |", "|---|---|---|---|---|---|"]
        for k, v in r.items():
            if "v0.6" in v:
                L.append(f"| {k} | {v['family']} | {v['events_mapped']} | {', '.join(v['expected'])} | "
                         f"{'detected' if v['v0.5']['as_expected'] else 'missed'} | {'detected' if v['v0.6']['as_expected'] else 'missed'} |")
            else:
                L.append(f"| {k} | {v['family']} | {v['events_mapped']} | {v['status']} | | |")
        L.append(f"\nScored {len(sc)}: v0.5 {sum(v['v0.5']['as_expected'] for v in sc)}, v0.6 {sum(v['v0.6']['as_expected'] for v in sc)}. "
                 f"Out of scope {sum(v['status'] == 'out of scope' for v in r.values())}, "
                 f"not readable {sum(v['status'] == 'not readable' for v in r.values())}.\n")
    p = out / "otrf_golden_saml.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += ["## OTRF Golden SAML (compound attack)", "",
              f"Expected: {', '.join(r['expected'])}. v0.5: {', '.join(r['v0.5']['detections']) or 'nothing'}. "
              f"v0.6: {', '.join(r['v0.6']['detections']) or 'nothing'}.", ""]
    p = out / "otrf_windows.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += ["## Windows endpoint logs (OTRF Security-Datasets)", "", "| Dataset | Tactic | Events | Detected |", "|---|---|---|---|"]
        L += [f"| {k} | {v['tactic']} | {v['events_mapped']} | {'yes' if v['v0.7']['as_expected'] else 'no'} |" for k, v in r.items()]
        L.append(f"\nDetected {sum(v['v0.7']['as_expected'] for v in r.values())} of {len(r)}.\n")
    p = out / "cert_budget.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += ["## CERT under a restriction budget (v0.9 protocol)", "", "| Release | Architecture | Detected | Prevented | Innocents L3+ / 1,000 | Case precision |", "|---|---|---|---|---|---|"]
        L += [f"| {rel} | {a} | {v['detected_pct']} % | {v['prevented_pct']} % | {v['false_l3_users_per_1000']} | {v['case_precision_pct']} |"
              for rel in ("r4.2", "r6.2", "r6.1") if rel in r for a, v in r[rel].items()]
        L.append("")
    p = out / "release_cert_r62_v08.json"
    if p.exists():
        r = json.loads(p.read_text())
        L += ["## CERT r6.2", "", "| Architecture | Insiders detected | Innocents L3+ / 1,000 | Case precision |", "|---|---|---|---|"]
        L += [f"| {k} | {round(v['detected_pct'] / 20)} of 5 | {v['false_l3_users_per_1000']} | {v['case_precision_pct']} % |" for k, v in r.items()]
        L.append("")
    og, ab = out / "orgforge.json", out / "orgforge_ablation.json"
    if og.exists():
        t = json.loads(og.read_text())["triage"]; v = json.loads(og.read_text())["verdict"]
        L += ["## OrgForge-IT public benchmark", "", "| System | Triage F1 | Verdict F1 | False-positive rate |", "|---|---|---|---|",
              f"| NullProtocol Negative Trust Architecture (deterministic) | {t['f1']:.3f} | {v['f1']:.3f} | {t['baseline_fp_rate']:.3f} |"]
        if ab.exists():
            a = json.loads(ab.read_text()).get("without person/account attribution") or {}
            if a:
                L.append(f"| NullProtocol Negative Trust Architecture without person/account attribution | {a['triage_f1']:.3f} | {a['verdict_f1']:.3f} | {a['baseline_fp_rate']:.3f} |")
        L += ["| Best published LLM pipelines (leaderboard, 2026-03-22) | 0.800 | 1.000 | 0.021 |", ""]
    md = "\n".join(L)
    (out / "RESULTS.md").write_text(md)
    return md
